class HealthCheckView(APIView):
    """
    Render Health Check Endpoint:
    Returns 200 OK with system diagnostic info (DB connectivity, OCR status, LLM provider).
    Used by Render's automated health check probe to confirm zero-downtime deployment readiness.
    """
    authentication_classes = []
    permission_classes = []

    def get(self, request):
        health_data = {
            "status": "healthy",
            "service": "masgeez-translator-backend",
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "environment": {
                "active_llm_provider": os.getenv("LLM_PROVIDER", "gemini"),
                "gemini_configured": bool(os.getenv("GEMINI_API_KEY") and os.getenv("GEMINI_API_KEY") != "your_gemini_api_key_here"),
                "groq_configured": bool(os.getenv("GROQ_API_KEY")),
            },
            "checks": {
                "database": "unknown",
                "tesseract_ocr": "unknown"
            }
        }

        # 1. Database Check
        try:
            connection.ensure_connection()
            health_data["checks"]["database"] = "connected"
        except Exception as db_err:
            health_data["status"] = "unhealthy"
            health_data["checks"]["database"] = f"error: {str(db_err)}"
            return Response(health_data, status=status.HTTP_503_SERVICE_UNAVAILABLE)

        # 2. Local Tesseract Check
        try:
            import pytesseract
            tess_cmd = getattr(pytesseract.pytesseract, 'tesseract_cmd', 'tesseract')
            if os.path.isfile(tess_cmd) or shutil.which(tess_cmd) or shutil.which('tesseract'):
                health_data["checks"]["tesseract_ocr"] = "available"
            else:
                health_data["checks"]["tesseract_ocr"] = "fallback_to_cloud_vision"
        except Exception:
            health_data["checks"]["tesseract_ocr"] = "fallback_to_cloud_vision"

        return Response(health_data, status=status.HTTP_200_OK)


class OCROnlyView(APIView):
    def post(self, request):
        file = request.FILES.get('file')
        if not file:
            return Response({"text": "No file received"}, status=400)
        
        # Fast local OCR: returns in < 0.5s
        lang = request.data.get('lang', 'amh')
        provider = request.data.get('provider')
        auto_clean = request.data.get('auto_clean', 'true').lower() == 'true'
        
        text = perform_hybrid_ocr(file.read(), lang=lang, provider=provider, auto_clean=auto_clean)
        active_provider = provider or os.getenv("LLM_PROVIDER", "gemini")
        return Response({"text": text, "provider": active_provider})

class CleanOCRView(APIView):
    def post(self, request):
        text = request.data.get('text', '')
        provider = request.data.get('provider')
        cleaned = restore_fidel_ocr_text(text, provider=provider)
        return Response({"text": cleaned})

class TranslateFlexibleView(APIView):
    def post(self, request):
        text = request.data.get('text', '')
        source = request.data.get('source', "Ge'ez")
        target = request.data.get('target', "Amharic")
        provider = request.data.get('provider')
        
        translation = translate_flexible(text, source, target, provider=provider)
        active_provider = provider or os.getenv("LLM_PROVIDER", "gemini")
        return Response({"translation": translation, "provider": active_provider})


class TranslateStreamView(APIView):
    """
    Server-Sent Events (SSE) Streaming Translation Endpoint:
    Yields chunks incrementally as they are generated by the LLM.
    Format:
      data: {"chunk": "..."}\n\n
      ...
      data: [DONE]\n\n
    """
    authentication_classes = []
    permission_classes = []

    def post(self, request):
        text = request.data.get('text', '')
        source = request.data.get('source', "Ge'ez")
        target = request.data.get('target', "Amharic")
        provider = request.data.get('provider')

        if not text or not text.strip():
            return Response({"error": "Empty text provided"}, status=status.HTTP_400_BAD_REQUEST)

        def event_stream():
            try:
                for chunk in translate_stream_flexible(text, source, target, provider=provider):
                    yield f"data: {json.dumps({'chunk': chunk})}\n\n"
                yield "data: [DONE]\n\n"
            except Exception as e:
                yield f"data: {json.dumps({'error': str(e)})}\n\n"
                yield "data: [DONE]\n\n"

        response = StreamingHttpResponse(event_stream(), content_type="text/event-stream; charset=utf-8")
        response["Cache-Control"] = "no-cache"
        response["X-Accel-Buffering"] = "no"
        return response
